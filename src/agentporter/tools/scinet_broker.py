"""Private host-side broker for the AgentPorter SciNet transport.

The AgentPorter process must not depend on a user's ``~/.ssh`` control socket.
This module provides a small, same-UID Unix-socket RPC boundary instead.  A
separately managed broker owns the authenticated SSH session and its private
control path; AgentPorter and delegated agents only see fixed SciNet actions.

The broker deliberately does not accept an SSH destination, SSH options, or a
shell command from a client.  Diagnostic requests are mapped to an enum here.
Training requests carry a command generated by AgentPorter's validated
training tool and are still sent through a fixed SSH envelope.
"""

from __future__ import annotations

import base64
import json
import os
import selectors
import shlex
import signal
import socket
import stat
import subprocess
import tempfile
import threading
from pathlib import Path
from typing import Any

from agentporter.tools.venkata import run_host_bytes

BROKER_PROTOCOL = 1
MAX_REQUEST = 8 * 1024 * 1024
MAX_RESPONSE = 4 * 1024 * 1024
DIAGNOSTIC_COMMANDS = {
    "gpu_partitions": ["sinfo", "-h", "-o", "%P|%D|%t|%G"],
    "gpu_nodes": ["sinfo", "-N", "-h", "-o", "%N|%G|%t"],
    "gpu_allocations": ["squeue", "-h", "-o", "%i|%u|%T|%b|%R"],
}
FORBIDDEN_REMOTE_TOKENS = {
    "ssh",
    "scp",
    "sftp",
    "sudo",
    "nc",
    "ncat",
    "curl",
    "wget",
    "socat",
}


def _b64(value: bytes) -> str:
    return base64.b64encode(value).decode("ascii")


def _unb64(value: Any) -> bytes:
    if not isinstance(value, str):
        raise ValueError("broker payload must be base64 text")
    return base64.b64decode(value.encode("ascii"), validate=True)


def _socket_path(value: str, label: str) -> str:
    path = os.path.realpath(os.path.expanduser(value or ""))
    if not path or path == "/":
        raise ValueError(f"SciNet {label} is not configured")
    if len(path) >= 100:
        raise ValueError(f"SciNet {label} is too long for Unix sockets")
    return path


def broker_socket_available(path: str) -> bool:
    try:
        info = os.stat(path, follow_symlinks=False)
    except OSError:
        return False
    return stat.S_ISSOCK(info.st_mode) and info.st_uid == os.getuid() and not info.st_mode & 0o077


def _control_socket_available(path: str) -> bool:
    try:
        info = os.stat(path, follow_symlinks=False)
    except OSError:
        return False
    return stat.S_ISSOCK(info.st_mode) and info.st_uid == os.getuid() and not info.st_mode & 0o077


def _ssh_envelope(host: str, user: str, control_socket: str, remote: list[str]) -> list[str]:
    """Build the only SSH envelope the broker can execute."""
    if not host or not user or not remote:
        raise ValueError("invalid SciNet broker request")
    if any(not isinstance(token, str) or "\x00" in token for token in remote):
        raise ValueError("invalid SciNet remote command")
    if any(token in FORBIDDEN_REMOTE_TOKENS for token in remote):
        raise PermissionError("broker remote command is not permitted")
    command = shlex.join(["exec", "/usr/bin/timeout", "120s", *remote])
    return [
        "/usr/bin/ssh",
        "-F",
        "/dev/null",
        "-T",
        "-S",
        control_socket,
        "-o",
        "BatchMode=yes",
        "-o",
        "StrictHostKeyChecking=yes",
        "-o",
        "ProxyCommand=/bin/false",
        "-o",
        "ControlMaster=no",
        "-o",
        "ControlPersist=no",
        "-o",
        "IdentityAgent=none",
        "-o",
        "PubkeyAuthentication=no",
        "-o",
        "PasswordAuthentication=no",
        "-o",
        "KbdInteractiveAuthentication=no",
        "-o",
        "HostbasedAuthentication=no",
        "-o",
        "ForwardAgent=no",
        "-o",
        "ClearAllForwardings=yes",
        "-l",
        user,
        host,
        shlex.join(["/bin/bash", "-lc", command]),
    ]


def broker_request(
    settings,
    remote: list[str],
    *,
    input_bytes: bytes | None = None,
    timeout: float = 60,
    max_output: int = 256 * 1024,
    operation: str = "training",
    command: str | None = None,
) -> dict:
    """Run one fixed request through the broker and mimic ``run_host_bytes``."""
    socket_path = _socket_path(getattr(settings, "broker_socket", ""), "broker socket")
    payload = {
        "version": BROKER_PROTOCOL,
        "operation": operation,
        "remote": remote,
        "input_length": len(input_bytes or b""),
        "timeout": min(max(float(timeout), 1.0), 900.0),
        "max_output": min(max(int(max_output), 1), MAX_RESPONSE),
    }
    if command is not None:
        payload["command"] = command
    raw_header = (json.dumps(payload, separators=(",", ":")) + "\n").encode("utf-8")
    if len(raw_header) > MAX_REQUEST:
        raise ValueError("SciNet broker request is too large")
    try:
        with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as channel:
            channel.settimeout(min(max(float(timeout) + 10, 10), 930))
            channel.connect(socket_path)
            channel.sendall(raw_header)
            if input_bytes:
                channel.sendall(input_bytes)
            response = bytearray()
            while len(response) <= MAX_REQUEST:
                chunk = channel.recv(65536)
                if not chunk:
                    break
                response.extend(chunk)
                if b"\n" in response:
                    break
    except (OSError, TimeoutError) as exc:
        return {
            "exit_code": None,
            "stdout": b"",
            "stderr": str(exc).encode("utf-8", errors="replace"),
            "timed_out": False,
            "truncated": False,
            "error": "scinet_broker_unavailable",
        }
    try:
        record = json.loads(bytes(response).split(b"\n", 1)[0])
        return {
            "exit_code": record.get("exit_code"),
            "stdout": _unb64(record.get("stdout", "")),
            "stderr": _unb64(record.get("stderr", "")),
            "timed_out": bool(record.get("timed_out", False)),
            "truncated": bool(record.get("truncated", False)),
            **({"error": record["error"]} if record.get("error") else {}),
        }
    except (ValueError, json.JSONDecodeError, KeyError) as exc:
        return {
            "exit_code": None,
            "stdout": b"",
            "stderr": str(exc).encode("utf-8", errors="replace"),
            "timed_out": False,
            "truncated": False,
            "error": "scinet_broker_protocol_error",
        }


class ScinetBroker:
    """Same-user RPC server that owns the private SSH transport."""

    def __init__(self, socket_path: str, control_socket: str, host: str, user: str):
        self.socket_path = _socket_path(socket_path, "broker socket")
        self.control_socket = _socket_path(control_socket, "broker control socket")
        self.host = host
        self.user = user

    def _authorized_peer(self, channel: socket.socket) -> bool:
        try:
            credentials = channel.getsockopt(socket.SOL_SOCKET, socket.SO_PEERCRED, 12)
            uid = int.from_bytes(credentials[4:8], byteorder="little")
            return uid == os.getuid()
        except (AttributeError, OSError):
            return False

    def _request(self, record: dict, body: bytes) -> dict:
        if record.get("version") != BROKER_PROTOCOL:
            raise ValueError("unsupported SciNet broker protocol")
        operation = record.get("operation")
        remote = record.get("remote")
        if operation not in {"diagnostic", "training"} or not isinstance(remote, list):
            raise ValueError("unsupported SciNet broker operation")
        length = record.get("input_length", 0)
        if not isinstance(length, int) or length < 0 or length != len(body):
            raise ValueError("invalid SciNet broker input length")
        if operation == "diagnostic":
            command = record.get("command")
            if command == "connection_status":
                remote = ["true"]
            elif command in DIAGNOSTIC_COMMANDS:
                remote = DIAGNOSTIC_COMMANDS[command]
            else:
                raise ValueError("unsupported SciNet diagnostic")
        if not _control_socket_available(self.control_socket):
            return {
                "exit_code": None,
                "stdout": "",
                "stderr": "",
                "timed_out": False,
                "truncated": False,
                "error": "scinet_auth_required",
            }
        argv = _ssh_envelope(self.host, self.user, self.control_socket, remote)
        result = run_host_bytes(
            argv,
            os.path.expanduser("~"),
            input_bytes=body or None,
            max_output=min(max(int(record.get("max_output", 1)), 1), MAX_RESPONSE),
            timeout=min(max(float(record.get("timeout", 60)), 1), 900) + 5,
        )
        return {
            "exit_code": result.get("exit_code"),
            "stdout": _b64(result.get("stdout", b"")),
            "stderr": _b64(result.get("stderr", b"")),
            "timed_out": bool(result.get("timed_out", False)),
            "truncated": bool(result.get("truncated", False)),
            "error": result.get("error"),
        }

    def handle(self, channel: socket.socket) -> None:
        if not self._authorized_peer(channel):
            return
        channel.settimeout(15)
        header = bytearray()
        while len(header) < MAX_REQUEST and b"\n" not in header:
            part = channel.recv(65536)
            if not part:
                return
            header.extend(part)
        try:
            line, remainder = bytes(header).split(b"\n", 1)
            record = json.loads(line)
            length = int(record.get("input_length", 0))
            body = bytearray(remainder)
            while len(body) < length:
                body.extend(channel.recv(min(1024 * 1024, length - len(body))))
            if len(body) != length:
                raise ValueError("truncated SciNet broker input")
            response = self._request(record, bytes(body))
        except Exception as exc:  # protocol errors never escape the daemon
            response = {
                "exit_code": None,
                "stdout": "",
                "stderr": "",
                "timed_out": False,
                "truncated": False,
                "error": type(exc).__name__,
            }
        channel.sendall((json.dumps(response, separators=(",", ":")) + "\n").encode("utf-8"))

    def serve(self) -> None:
        parent = str(Path(self.socket_path).parent)
        os.makedirs(parent, mode=0o700, exist_ok=True)
        try:
            os.unlink(self.socket_path)
        except FileNotFoundError:
            pass
        with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as listener:
            listener.bind(self.socket_path)
            os.chmod(self.socket_path, 0o600)
            listener.listen(8)
            while True:
                channel, _ = listener.accept()
                threading.Thread(target=self._serve_one, args=(channel,), daemon=True).start()

    def _serve_one(self, channel: socket.socket) -> None:
        try:
            with channel:
                self.handle(channel)
        except OSError:
            pass


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="AgentPorter SciNet broker")
    parser.add_argument("--socket", required=True)
    parser.add_argument("--control-socket", required=True)
    parser.add_argument("--host", required=True)
    parser.add_argument("--user", required=True)
    args = parser.parse_args()
    ScinetBroker(args.socket, args.control_socket, args.host, args.user).serve()


if __name__ == "__main__":
    main()
