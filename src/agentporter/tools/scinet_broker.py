# Independent review pins: never derive these from a caller or the inference module.
INFERENCE_RESULTS_READER_SHA256 = "c0bb58eefab06f9bb5428b422d920168eb1a4de363c401054dd6d1b0140e7a61"
# Read-only Laya runtime inspect driver: occupies no GPU and uses no network.
INFERENCE_PROVISION_INSPECT_SHA256 = (
    "d3992e6ab3cf35c142e667d2d796b62e4fd7dbe469b2b25ecf5cb14f40946b64"
)
# Immutable reviewed-package receiver for the provision-source landing.
INFERENCE_PROVISION_SOURCES_RECEIVER_SHA256 = (
    "724b0a0ea4caffb97a84fdc37bfc43b31c65cbc88e65fbe4a578c719fbdc4981"
)
# Digest-pinned Laya prepare driver; accepts no stdin, no Slurm, no GPU.
INFERENCE_PROVISION_PREPARE_SHA256 = (
    "7aeb0c553906a1e06bd49e8d9c771c1bb764c24ff35676a632b771b18febe559"
)
PROVISION_SOURCES_MAX_INPUT_BYTES = 32 * 1024 * 1024


def _provision_path_checks(scratch, cache):
    pattern = r"/scratch/[A-Za-z0-9_./-]+"
    return (
        not re.fullmatch(pattern, scratch) or ".." in scratch.split("/")
        or "//" in scratch
        or not re.fullmatch(pattern, cache) or ".." in cache.split("/")
        or "//" in cache
        or not cache.startswith(scratch + "/") or cache == scratch
    )


def inference_provision_sources_command(remote: list[str]) -> str:
    """Allow only the digest-pinned reviewed-package receiver for a fixed landing."""
    if (not isinstance(remote, list) or len(remote) != 5
            or any(not isinstance(token, str) or "\x00" in token for token in remote)
            or remote[1] != "-c"):
        raise PermissionError("invalid inference provision sources argv")
    python, _c, script, root, stage = remote
    scratch = root.rsplit("/", 1)[0] if "/" in root else ""
    if (python != "/usr/bin/python3"
            or not re.fullmatch(r"/[A-Za-z0-9_./-]+", python) or ".." in python.split("/")
            or "..." in python or "//" in python
            or hashlib.sha256(script.encode("utf-8")).hexdigest()
            != INFERENCE_PROVISION_SOURCES_RECEIVER_SHA256
            or not re.fullmatch(r"/scratch/[A-Za-z0-9_./-]+", root)
            or ".." in root.split("/") or "//" in root
            or not root.endswith("/provision-sources") or root == "/provision-sources"
            or not scratch.strip("/")
            or not re.fullmatch(r"[0-9a-f]{32}", stage)):
        raise PermissionError("invalid inference provision sources arguments")
    # sshd still invokes the account shell; its startup behavior remains trusted.
    return shlex.join(["exec", "/usr/bin/env", "-i", "PATH=/usr/bin:/bin",
                       "/usr/bin/timeout", "920s", *remote])


def inference_provision_prepare_command(remote: list[str]) -> str:
    """Allow only the digest-pinned prepare driver with its fixed arguments."""
    if (not isinstance(remote, list) or len(remote) != 12
            or any(not isinstance(token, str) or "\x00" in token for token in remote)
            or remote[:4] != ["/usr/bin/python3", "-I", "-B", "-c"]):
        raise PermissionError("invalid inference provision prepare argv")
    script, mode, bootstrap, scratch, cache, run_id, bundle, digest = remote[4:]
    if hashlib.sha256(script.encode("utf-8")).hexdigest() != INFERENCE_PROVISION_PREPARE_SHA256:
        raise PermissionError("inference provision prepare digest mismatch")
    bundle_prefixes = (scratch + "/provision-sources/", scratch + "/stages/")
    if (mode != "prepare"
            or _provision_path_checks(scratch, cache)
            or bootstrap != "/usr/bin/python3"
            or not re.fullmatch(r"/[A-Za-z0-9_./-]+", bootstrap)
            or ".." in bootstrap.split("/") or "//" in bootstrap
            or not re.fullmatch(r"[0-9a-f]{32}", run_id)
            or len(bundle) > 200
            or not any(bundle.startswith(prefix)
                       and re.fullmatch(r"[0-9a-f]{32}", bundle[len(prefix):])
                       for prefix in bundle_prefixes)
            or not (digest == "none" or re.fullmatch(r"[0-9a-f]{64}", digest))):
        raise PermissionError("invalid inference provision prepare arguments")
    # sshd still invokes the account shell; its startup behavior remains trusted.
    return shlex.join(["exec", "/usr/bin/env", "-i", "PATH=/usr/bin:/bin",
                       "/usr/bin/timeout", "920s", *remote])


def inference_provision_command(remote: list[str]) -> str:
    """Allow only the digest-pinned read-only runtime inspect remote argv."""
    if (not isinstance(remote, list) or len(remote) != 10
            or any(not isinstance(token, str) or "\x00" in token for token in remote)
            or remote[:4] != ["/usr/bin/python3", "-I", "-B", "-c"]):
        raise PermissionError("invalid inference provision argv")
    script, mode, bootstrap, scratch, cache, run_id = remote[4:]
    if (hashlib.sha256(script.encode("utf-8")).hexdigest()
            != INFERENCE_PROVISION_INSPECT_SHA256):
        raise PermissionError("inference provision inspect digest mismatch")
    path_pattern = r"/scratch/[A-Za-z0-9_./-]+"
    exe_pattern = r"/[A-Za-z0-9_./-]+"
    if (mode != "inspect"
            or bootstrap != "/usr/bin/python3"
            or not re.fullmatch(exe_pattern, bootstrap) or ".." in bootstrap.split("/")
            or not re.fullmatch(path_pattern, scratch) or ".." in scratch.split("/")
            or "//" in scratch
            or not re.fullmatch(path_pattern, cache) or ".." in cache.split("/")
            or "//" in cache
            or not cache.startswith(scratch + "/") or cache == scratch
            or not re.fullmatch(r"[0-9a-f]{32}", run_id)):
        raise PermissionError("invalid inference provision arguments")
    # sshd still invokes the account shell; its startup behavior remains trusted.
    return shlex.join(["exec", "/usr/bin/env", "-i", "PATH=/usr/bin:/bin",
                       "/usr/bin/timeout", "150s", *remote])


def inference_results_command(remote: list[str]) -> str:
    """Allow only the reviewed results reader and its four bounded arguments."""
    if (not isinstance(remote, list) or len(remote) != 9
            or any(not isinstance(token, str) or "\x00" in token for token in remote)
            or remote[:4] != ["/usr/bin/python3", "-I", "-B", "-c"]):
        raise PermissionError("invalid inference results argv")
    script, scratch, job, stage, cases = remote[4:]
    if hashlib.sha256(script.encode("utf-8")).hexdigest() != INFERENCE_RESULTS_READER_SHA256:
        raise PermissionError("inference results reader digest mismatch")
    case_ids = cases.split(",")
    if (not re.fullmatch(r"/scratch/[A-Za-z0-9_./-]+", scratch)
            or ".." in scratch.split("/") or "//" in scratch
            or not re.fullmatch(r"[1-9][0-9]{0,19}", job)
            or not re.fullmatch(r"[0-9a-f]{32}", stage)
            or len(case_ids) != 42 or len(set(case_ids)) != 42
            or any(not re.fullmatch(r"P[0-9]{4}_(?:pos|ctl)", case) for case in case_ids)):
        raise PermissionError("invalid inference results arguments")
    # sshd still invokes the account shell; its startup behavior remains trusted.
    return shlex.join(["exec", "/usr/bin/env", "-i", "PATH=/usr/bin:/bin",
                       "/usr/bin/timeout", "60s", *remote])


def _b64(value: bytes) -> str:
    return base64.b64encode(value).decode("ascii")


def _unb64(value: Any) -> bytes:
    if not isinstance(value, str):
        raise ValueError("broker payload must be base64 text")
    return base64.b64decode(value.encode("ascii"), validate=True)


def _socket_path(value: str, label: str) -> str:
    path = os.path.realpath(os.path.expanduser(value or ""))
    if not path or path == "/":
        raise ValueError(f"SciNet {label} is not configured")
    if len(path) >= 100:
        raise ValueError(f"SciNet {label} is too long for Unix sockets")
    return path


def broker_socket_available(path: str) -> bool:
    try:
        info = os.stat(path, follow_symlinks=False)
    except OSError:
        return False
    return stat.S_ISSOCK(info.st_mode) and info.st_uid == os.getuid() and not info.st_mode & 0o077


def _control_socket_available(path: str) -> bool:
    try:
        info = os.stat(path, follow_symlinks=False)
    except OSError:
        return False
    return stat.S_ISSOCK(info.st_mode) and info.st_uid == os.getuid() and not info.st_mode & 0o077


def _ssh_envelope(host: str, user: str, control_socket: str, remote: list[str],
                  *, operation: str = "training") -> list[str]:
    """Build the only SSH envelope the broker can execute."""
    if not host or not user or not remote:
        raise ValueError("invalid SciNet broker request")
    if any(not isinstance(token, str) or "\x00" in token for token in remote):
        raise ValueError("invalid SciNet remote command")
    if any(token in FORBIDDEN_REMOTE_TOKENS for token in remote):
        raise PermissionError("broker remote command is not permitted")
    if operation == "inference_results":
        command = inference_results_command(remote)
    elif operation == "inference_provision":
        command = inference_provision_command(remote)
    elif operation == "inference_provision_sources":
        command = inference_provision_sources_command(remote)
    elif operation == "inference_provision_prepare":
        command = inference_provision_prepare_command(remote)
    else:
        command = shlex.join(["/bin/bash", "-lc", shlex.join(
            ["exec", "/usr/bin/timeout", "120s", *remote])])
    return [
        "/usr/bin/ssh",
        "-F",
        "/dev/null",
        "-T",
        "-S",
        control_socket,
        "-o",
        "BatchMode=yes",
        "-o",
        "StrictHostKeyChecking=yes",
        "-o",
        "ProxyCommand=/bin/false",
        "-o",
        "ControlMaster=no",
        "-o",
        "ControlPersist=no",
        "-o",
        "IdentityAgent=none",
        "-o",
        "PubkeyAuthentication=no",
        "-o",
        "PasswordAuthentication=no",
        "-o",
        "KbdInteractiveAuthentication=no",
        "-o",
        "HostbasedAuthentication=no",
        "-o",
        "ForwardAgent=no",
        "-o",
        "ClearAllForwardings=yes",
        *(["-n"] if operation in {"inference_results", "inference_provision",
                                  "inference_provision_prepare"} else []),
        "-l",
        user,
        host,
        command,
    ]


def _login_failure_reason(
    output: bytes, *, push_requested: bool, exit_status: int, timed_out: bool
) -> str:
    """Map private SSH terminal output to a small, non-sensitive reason enum."""
    for pattern, reason in LOGIN_FAILURE_PATTERNS:
        if pattern.search(output):
            return reason
    if timed_out:
        if push_requested:
            return "duo_approval_timeout"
        if re.search(rb"duo", output, re.I):
            return "duo_prompt_unrecognized"
        if OTHER_AUTH_PROMPT.search(output):
            return "authentication_prompt_unrecognized"
        return "ssh_output_without_known_prompt" if output else "no_ssh_prompt"
    if not output and exit_status == 127:
        return "ssh_start_failed"
    return "login_process_exited"


def _has_duo_push_prompt(output: bytes) -> bool:
    terminal_text = ANSI_TERMINAL_SEQUENCE.sub(b"", output)
    terminal_text = terminal_text.replace(b"\r", b"\n").replace(b"\x08", b"")
    return DUO_PUSH_PROMPT.search(terminal_text) is not None


def broker_request(
    settings,
    remote: list[str],
    *,
    input_bytes: bytes | None = None,
    timeout: float = 60,
    max_output: int = 256 * 1024,
    operation: str = "training",
    command: str | None = None,
) -> dict:
    """Run one fixed request through the broker and mimic ``run_host_bytes``."""
    socket_path = _socket_path(getattr(settings, "broker_socket", ""), "broker socket")
    payload = {
        "version": BROKER_PROTOCOL,
        "operation": operation,
        "remote": remote,
        "input_length": len(input_bytes or b""),
        "timeout": min(max(float(timeout), 1.0), 900.0),
        "max_output": min(max(int(max_output), 1), MAX_RESPONSE),
    }
    if command is not None:
        payload["command"] = command
    raw_header = (json.dumps(payload, separators=(",", ":")) + "\n").encode("utf-8")
    if len(raw_header) > MAX_REQUEST:
        raise ValueError("SciNet broker request is too large")
    try:
        with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as channel:
            channel.settimeout(min(max(float(timeout) + 10, 10), 930))
            channel.connect(socket_path)
            channel.sendall(raw_header)
            if input_bytes:
                channel.sendall(input_bytes)
            response = bytearray()
            while len(response) <= MAX_REQUEST:
                chunk = channel.recv(65536)
                if not chunk:
                    break
                response.extend(chunk)
                if b"\n" in response:
                    break
    except (OSError, TimeoutError) as exc:
        return {
            "exit_code": None,
            "stdout": b"",
            "stderr": str(exc).encode("utf-8", errors="replace"),
            "timed_out": False,
            "truncated": False,
            "error": "scinet_broker_unavailable",
        }
    try:
        record = json.loads(bytes(response).split(b"\n", 1)[0])
        return {
            **({"state": record["state"]} if record.get("state") else {}),
            **({"success": bool(record["success"])} if "success" in record else {}),
            **({"reason": record["reason"]} if record.get("reason") else {}),
            "exit_code": record.get("exit_code"),
            "stdout": _unb64(record.get("stdout", "")),
            "stderr": _unb64(record.get("stderr", "")),
            "timed_out": bool(record.get("timed_out", False)),
            "truncated": bool(record.get("truncated", False)),
            **({"error": record["error"]} if record.get("error") else {}),
        }
    except (ValueError, json.JSONDecodeError, KeyError) as exc:
        return {
            "exit_code": None,
            "stdout": b"",
            "stderr": str(exc).encode("utf-8", errors="replace"),
            "timed_out": False,
            "truncated": False,
            "error": "scinet_broker_protocol_error",
        }


class ScinetBroker:
    """Same-user RPC server that owns the private SSH transport."""

    def __init__(self, socket_path: str, control_socket: str, host: str, user: str):
        self.socket_path = _socket_path(socket_path, "broker socket")
        self.control_socket = _socket_path(control_socket, "broker control socket")
        self.login_control_socket = _socket_path(
            str(Path(self.socket_path).parent / "scinet-control"),
            "login control socket",
        )
        self.host = host
        self.user = user
        self._login_lock = threading.Lock()
        self._login_state = "not_started"
        self._login_reason: str | None = None
        self._login_started = 0.0

    def _master_is_running(self, path: str | None = None) -> bool:
        path = path or self.control_socket
        if not _control_socket_available(path):
            return False
        try:
            result = subprocess.run(
                [
                    "/usr/bin/ssh", "-F", "/dev/null", "-S", path,
                    "-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=yes",
                    "-o", "ProxyCommand=/bin/false", "-l", self.user,
                    "-O", "check", self.host,
                ],
                stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL, timeout=5, check=False,
            )
            if result.returncode != 0:
                return False
            # A mux listener can survive a dead TCP connection. Verify the
            # cluster responds without permitting a fresh authentication.
            probe = subprocess.run(
                [
                    "/usr/bin/ssh", "-F", "/dev/null", "-S", path, "-T",
                    "-o", "BatchMode=yes", "-o", "StrictHostKeyChecking=yes",
                    "-o", "ProxyCommand=/bin/false", "-o", "ControlMaster=no",
                    "-o", "ForwardAgent=no", "-o", "ClearAllForwardings=yes",
                    "-l", self.user, self.host, "/usr/bin/true",
                ],
                stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL, timeout=5, check=False,
            )
            return probe.returncode == 0
        except (OSError, subprocess.TimeoutExpired):
            return False

    def _login_status(self) -> dict[str, Any]:
        if self._master_is_running(self.login_control_socket) or self._master_is_running():
            with self._login_lock:
                self._login_state = "authenticated"
                self._login_reason = None
            return {"state": "authenticated", "success": True}
        with self._login_lock:
            if self._login_state == "authenticated":
                self._login_state = "failed"
                self._login_reason = "scinet_connection_unresponsive"
            state = self._login_state
            reason = self._login_reason
        return {"state": state, "success": False, **({"reason": reason} if reason else {})}

    def _login_argv(self, control_socket: str | None = None) -> list[str]:
        return [
            "/usr/bin/ssh", "-F", "/dev/null", "-M", "-S",
            control_socket or self.login_control_socket,
            "-N", "-T", "-f", "-o", "ControlPersist=12h", "-o", "BatchMode=no",
            "-o", "ServerAliveInterval=30", "-o", "ServerAliveCountMax=3",
            # Some SciNet accounts require an existing host public key before Duo.
            "-o", "PreferredAuthentications=publickey,keyboard-interactive",
            "-o", "KbdInteractiveAuthentication=yes", "-o", "HostbasedAuthentication=no",
            "-o", "PubkeyAuthentication=yes", "-o", "PasswordAuthentication=no",
            "-o", "StrictHostKeyChecking=yes", "-o", "ClearAllForwardings=yes",
            "-o", "ForwardAgent=no",
            "-l", self.user, self.host,
        ]

    def _login_worker(self, pid: int, master_fd: int, control_socket: str) -> None:
        deadline = time.monotonic() + LOGIN_TIMEOUT_SECONDS
        output = bytearray()
        push_requested = False
        exit_status: int | None = None
        timed_out = False
        try:
            os.set_blocking(master_fd, False)
            while time.monotonic() < deadline:
                ready, _, _ = select.select([master_fd], [], [], 0.2)
                if ready:
                    try:
                        chunk = os.read(master_fd, 4096)
                    except OSError:
                        chunk = b""
                    if chunk:
                        output.extend(chunk)
                        if len(output) > 32768:
                            del output[:-4096]
                        if not push_requested and _has_duo_push_prompt(bytes(output)):
                            # This selects the push factor only; it is not a Duo approval/code.
                            try:
                                os.write(master_fd, b"1\n")
                            except OSError:
                                break
                            push_requested = True
                            with self._login_lock:
                                self._login_state = "push_requested"
                    else:
                        break
                waited, status = os.waitpid(pid, os.WNOHANG)
                if waited:
                    exit_status = os.waitstatus_to_exitcode(status)
                    break
            if exit_status is None:
                timed_out = True
                try:
                    os.kill(pid, signal.SIGTERM)
                except ProcessLookupError:
                    pass
                _, status = os.waitpid(pid, 0)
                exit_status = os.waitstatus_to_exitcode(status)
            if self._master_is_running(control_socket):
                state = "authenticated"
                reason = None
            elif push_requested:
                state = "failed" if timed_out or exit_status else "pending_approval"
                reason = _login_failure_reason(
                    bytes(output), push_requested=True,
                    exit_status=exit_status or 0, timed_out=timed_out,
                ) if state == "failed" else None
            else:
                state = "failed"
                reason = _login_failure_reason(
                    bytes(output), push_requested=False,
                    exit_status=exit_status or 0, timed_out=timed_out,
                )
            with self._login_lock:
                self._login_state = state
                self._login_reason = reason
            if reason:
                logger.warning("SciNet login finished: state=%s reason=%s", state, reason)
            else:
                logger.info("SciNet login finished: state=%s", state)
        finally:
            os.close(master_fd)

    def _authorized_peer(self, channel: socket.socket) -> bool:
        try:
            credentials = channel.getsockopt(socket.SOL_SOCKET, socket.SO_PEERCRED, 12)
            uid = int.from_bytes(credentials[4:8], byteorder="little")
            return uid == os.getuid()
        except (AttributeError, OSError):
            return False

    def _request(self, record: dict, body: bytes) -> dict:
        if record.get("version") != BROKER_PROTOCOL:
            raise ValueError("unsupported SciNet broker protocol")
        operation = record.get("operation")
        remote = record.get("remote")
        if operation == "login":
            if remote != [] or body or record.get("input_length", 0) != 0:
                raise ValueError("invalid SciNet login request")
            command = record.get("command")
            if command == "status":
                return self._login_status()
            if command != "start":
                raise ValueError("unsupported SciNet login action")
            if self._master_is_running(self.login_control_socket) or self._master_is_running():
                with self._login_lock:
                    self._login_state = "authenticated"
                    self._login_reason = None
                return {"state": "authenticated", "success": True}
            if os.path.lexists(self.login_control_socket):
                logger.warning("SciNet login not started: reason=stale_control_socket")
                return {"state": "failed", "success": False, "reason": "stale_control_socket"}
            with self._login_lock:
                now = time.monotonic()
                if self._login_state in {"starting", "push_requested", "pending_approval"}:
                    return {
                        "state": self._login_state,
                        "success": False,
                        **({"reason": self._login_reason} if self._login_reason else {}),
                    }
                if self._login_started and now - self._login_started < LOGIN_COOLDOWN_SECONDS:
                    return {"state": "cooldown", "success": False, "reason": "retry_cooldown"}
                self._login_started = now
                self._login_state = "starting"
                self._login_reason = None
            pid, master_fd = pty.fork()
            if pid == 0:
                try:
                    os.execv("/usr/bin/ssh", self._login_argv(self.login_control_socket))
                except BaseException:
                    os._exit(127)
            threading.Thread(
                target=self._login_worker,
                args=(pid, master_fd, self.login_control_socket),
                daemon=True,
            ).start()
            return {"state": "starting", "success": False}
        if operation not in {"diagnostic", "training", "inference_results",
                             "inference_provision", "inference_provision_sources",
                             "inference_provision_prepare"} or not isinstance(remote, list):
            raise ValueError("unsupported SciNet broker operation")
        length = record.get("input_length", 0)
        if not isinstance(length, int) or length < 0 or length != len(body):
            raise ValueError("invalid SciNet broker input length")
        if operation == "inference_results":
            if body or length != 0 or record.get("command") is not None:
                raise PermissionError("inference results accepts no stdin or command")
            inference_results_command(remote)
        if operation == "inference_provision":
            if body or length != 0 or record.get("command") is not None:
                raise PermissionError("inference provision accepts no stdin or command")
            inference_provision_command(remote)
        if operation == "inference_provision_sources":
            if record.get("command") is not None:
                raise PermissionError("inference provision sources accepts no command")
            inference_provision_sources_command(remote)
            if length > PROVISION_SOURCES_MAX_INPUT_BYTES:
                raise PermissionError("inference provision sources stdin exceeds 32 MiB")
            if length < 1:
                raise PermissionError("inference provision sources requires an stdin header")
        if operation == "inference_provision_prepare":
            if body or length != 0 or record.get("command") is not None:
                raise PermissionError("inference provision prepare accepts no stdin or command")
            inference_provision_prepare_command(remote)
        if operation == "diagnostic":
            command = record.get("command")
            if command == "connection_status":
                remote = ["true"]
            elif command in DIAGNOSTIC_COMMANDS:
                remote = DIAGNOSTIC_COMMANDS[command]
            else:
                raise ValueError("unsupported SciNet diagnostic")
        if not (
            _control_socket_available(self.login_control_socket)
            or _control_socket_available(self.control_socket)
        ):
            return {
                "exit_code": None,
                "stdout": "",
                "stderr": "",
                "timed_out": False,
                "truncated": False,
                "error": "scinet_auth_required",
            }
        control_socket = (
            self.login_control_socket
            if _control_socket_available(self.login_control_socket)
            else self.control_socket
        )
        argv = _ssh_envelope(self.host, self.user, control_socket, remote, operation=operation)
        result = run_host_bytes(
            argv,
            os.path.expanduser("~"),
            input_bytes=body or None,
            max_output=min(max(int(record.get("max_output", 1)), 1), MAX_RESPONSE),
            timeout=min(max(float(record.get("timeout", 60)), 1), 900) + 5,
        )
        return {
            "exit_code": result.get("exit_code"),
            "stdout": _b64(result.get("stdout", b"")),
            "stderr": _b64(result.get("stderr", b"")),
            "timed_out": bool(result.get("timed_out", False)),
            "truncated": bool(result.get("truncated", False)),
            "error": result.get("error"),
        }

    def handle(self, channel: socket.socket) -> None:
        if not self._authorized_peer(channel):
            return
        channel.settimeout(15)
        header = bytearray()
        while len(header) < MAX_REQUEST and b"\n" not in header:
            part = channel.recv(65536)
            if not part:
                return
            header.extend(part)
        try:
            line, remainder = bytes(header).split(b"\n", 1)
            record = json.loads(line)
            length = int(record.get("input_length", 0))
            body = bytearray(remainder)
            while len(body) < length:
                body.extend(channel.recv(min(1024 * 1024, length - len(body))))
            if len(body) != length:
                raise ValueError("truncated SciNet broker input")
            response = self._request(record, bytes(body))
        except Exception as exc:  # protocol errors never escape the daemon
            response = {
                "exit_code": None,
                "stdout": "",
                "stderr": "",
                "timed_out": False,
                "truncated": False,
                "error": type(exc).__name__,
            }
        channel.sendall((json.dumps(response, separators=(",", ":")) + "\n").encode("utf-8"))

    def serve(self) -> None:
        parent = str(Path(self.socket_path).parent)
        os.makedirs(parent, mode=0o700, exist_ok=True)
        try:
            os.unlink(self.socket_path)
        except FileNotFoundError:
            pass
        with socket.socket(socket.AF_UNIX, socket.SOCK_STREAM) as listener:
            listener.bind(self.socket_path)
            os.chmod(self.socket_path, 0o600)
            listener.listen(8)
            while True:
                channel, _ = listener.accept()
                threading.Thread(target=self._serve_one, args=(channel,), daemon=True).start()

    def _serve_one(self, channel: socket.socket) -> None:
        try:
            with channel:
                self.handle(channel)
        except OSError:
            pass


